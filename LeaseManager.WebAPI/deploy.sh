#!/bin/bash

# Script de déploiement et lancement de l'application

echo "???????????????????????????????????????????????????????????"
echo "  LeaseManager API - Script de Déploiement"
echo "???????????????????????????????????????????????????????????"

# Variables
ENVIRONMENT=${1:-Development}
BUILD_CONFIG=${2:-Debug}

echo ""
echo "Configuration: $BUILD_CONFIG"
echo "Environnement: $ENVIRONMENT"
echo ""

# Fonction pour vérifier les erreurs
check_error() {
    if [ $? -ne 0 ]; then
        echo "? Erreur: $1"
        exit 1
  fi
}

# 1. Restaurer les dépendances
echo "1??  Restauration des dépendances NuGet..."
dotnet restore
check_error "Restauration des dépendances échouée"
echo "? Dépendances restaurées"

# 2. Nettoyer les builds précédents
echo ""
echo "2??  Nettoyage des builds précédents..."
dotnet clean --configuration $BUILD_CONFIG
check_error "Nettoyage échoué"
echo "? Builds précédents nettoyés"

# 3. Construire la solution
echo ""
echo "3??  Compilation de la solution..."
dotnet build --configuration $BUILD_CONFIG
check_error "Compilation échouée"
echo "? Compilation réussie"

# 4. Exécuter les tests
echo ""
echo "4??  Exécution des tests unitaires..."
dotnet test --configuration $BUILD_CONFIG --verbosity normal
check_error "Tests échoués"
echo "? Tous les tests passent"

# 5. Publier l'application
if [ "$BUILD_CONFIG" == "Release" ]; then
    echo ""
    echo "5??  Publication en Release..."
    dotnet publish -c Release -o ./publish
    check_error "Publication échouée"
    echo "? Application publiée"
    echo ""
    echo "?? Fichiers de publication dans: ./publish"
fi

# 6. Information de lancement
echo ""
echo "???????????????????????????????????????????????????????????"
echo "  ? Déploiement Terminé"
echo "???????????????????????????????????????????????????????????"
echo ""
echo "Pour lancer l'application:"
echo ""
if [ "$BUILD_CONFIG" == "Debug" ]; then
    echo "  dotnet run"
    echo ""
    echo "Accédez à l'API à:"
    echo "  ?? http://localhost:5000"
    echo "?? Swagger: http://localhost:5000/"
else
    echo "  cd publish"
    echo "  dotnet LeaseManager.WebAPI.dll"
fi
echo ""
echo "Health Check: http://localhost:5000/api/health"
echo ""